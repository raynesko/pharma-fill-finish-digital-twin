"""Regenerate the analytical cross-check table in docs/verification.md (T4.1.2).

Usage: python tools/verification_report.py
Rewrites only the text between the BEGIN/END analytic markers.
"""

import time
from pathlib import Path

from ffdt.config import load_config
from ffdt.experiments import analytic as A
from ffdt.metrics import ledger as L
from ffdt.sim.line import Line

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "verification.md"
BEGIN, END = "<!-- BEGIN analytic (generated) -->", "<!-- END analytic -->"


def main() -> None:
    t0 = time.time()
    checks = [A.mm1_wait(), A.mm1k_block(), A.availability()]
    rows = [
        "| Check | Theory | Simulated mean | 95% CI | Rel. error | Theory in CI | Reps |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in checks:
        rows.append(
            f"| {c.name} | {c.theory:.5f} | {c.mean:.5f} | [{c.ci_low:.5f}, {c.ci_high:.5f}] "
            f"| {c.rel_error:+.2%} | {'yes' if c.theory_in_ci else '**NO**'} | {c.n_reps} |"
        )
    line = Line(load_config(ROOT / "configs" / "baseline_line.yaml"), root_seed=20261116)
    line.run()
    q = L.queue_stats(line.export())
    rows += [
        "",
        "Little's Law on every buffer, baseline draft config, seed 20261116, replication 0"
        " (L time-weighted; λ arrivals per minute; W from matched entry/exit times):",
        "",
        "| Buffer | L (sub-lots) | λ (per min) | W (min) | λW | Rel. error |",
        "|---|---|---|---|---|---|",
    ]
    for r in q.itertuples():
        lw = r.lambda_per_min * r.mean_wait_min
        rows.append(
            f"| `{r.buffer}` | {r.mean_sublots:.4f} | {r.lambda_per_min:.4f} | "
            f"{r.mean_wait_min:.3f} | {lw:.4f} | {r.littles_ratio - 1:+.1e} |"
        )
    rows.append("")
    rows.append(f"Generated by `tools/verification_report.py` in {time.time() - t0:.0f} s.")
    text = DOC.read_text(encoding="utf-8")
    i, j = text.index(BEGIN) + len(BEGIN), text.index(END)
    DOC.write_text(text[:i] + "\n" + "\n".join(rows) + "\n" + text[j:], encoding="utf-8")
    print(f"updated {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
