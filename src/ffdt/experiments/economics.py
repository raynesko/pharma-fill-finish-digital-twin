"""Illustrative economics (T5.2.4): output gains turned into money with PLACEHOLDER prices.

Not a business case. The only RESULT inputs are the paired scenario effects in
``reports/results_final.json``; every price, cost and the weeks per year are PLACEHOLDER or
ASSUMPTION values with ranges, chosen to show the arithmetic, not sourced from any plant or
vendor. The point is the shape of the answer (which lever can pay back at all, and how fast
payback moves with the value of a vial), not the dollar amounts.

    python -m ffdt.experiments.economics     # writes docs/economics.md
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
FINAL = ROOT / "reports" / "results_final.json"
DOC = ROOT / "docs" / "economics.md"
BASELINE = ROOT / "configs" / "baseline_line.yaml"

# Every value here is PLACEHOLDER (no source) or ASSUMPTION; (low, mid, high).
WEEKS_PER_YEAR = (44, 48, 50)  # ASSUMPTION: production weeks per year, the rest shutdowns
MARGIN_PER_VIAL = (0.5, 2.0, 10.0)  # PLACEHOLDER, $ contribution per extra good vial sold
LEVERS = {
    # scenario id: (what is paid, one-time cost range $, recurring cost range $/yr)
    "sc04_changeover_m25": ("SMED project, changeovers -25%", (50e3, 150e3, 300e3), None),
    "sc04_changeover_m50": ("SMED project, changeovers -50%", (150e3, 400e3, 1e6), None),
    "sc01_avi_plus1": ("Second automated inspection machine", (0.8e6, 1.5e6, 3e6), None),
    "sc03_operator_plus1": (
        "One more line operator per shift (2 shifts)",
        None,
        (120e3, 180e3, 260e3),
    ),
}


def ppt_hours_per_week() -> float:
    """Scheduled production hours per week from the frozen baseline calendar."""
    from ffdt.config import load_config

    c = load_config(BASELINE).calendar
    return c.days * c.shifts_per_day * (c.shift_min - c.break_min_per_shift) / 60


def rows(d: dict) -> list[dict]:
    """Annual extra good vials (mean and CI low) and payback per lever at the mid prices."""
    scen = {s["scenario"]: s for s in d["scenarios"]}
    base = d["baseline"]["good_per_ppt_hour"]["mean"]
    hours = ppt_hours_per_week() * WEEKS_PER_YEAR[1]
    out = []
    for sid, (what, capex, opex) in LEVERS.items():
        s = scen[sid]
        vph = s["good_per_ppt_hour_diff"]
        vph_low = s["pct_ci_low"] * base
        r = {
            "scenario": sid,
            "plain_name": s["plain_name"],
            "what": what,
            "capex": capex,
            "opex": opex,
            "detectable": s["pct_ci_low"] > 0 or s["pct_ci_high"] < 0,
            "pct": s["pct_diff"],
            "pct_ci": (s["pct_ci_low"], s["pct_ci_high"]),
            "vials_yr": vph * hours,
            "vials_yr_low": vph_low * hours,
        }
        r["value_yr"] = {m: r["vials_yr"] * m for m in MARGIN_PER_VIAL}
        if capex:
            r["payback_months"] = {
                m: (capex[1] / v * 12 if (v := r["vials_yr_low"] * m) > 0 else None)
                for m in MARGIN_PER_VIAL
            }
            r["breakeven_margin_12m"] = (
                capex[1] / r["vials_yr_low"] if r["vials_yr_low"] > 0 else None
            )
            # worst corner: high cost, low margin, CI-low gain, fewest weeks
            v = r["vials_yr_low"] * WEEKS_PER_YEAR[0] / WEEKS_PER_YEAR[1] * MARGIN_PER_VIAL[0]
            r["worst_months"] = capex[2] / v * 12 if v > 0 else None
        if opex:
            r["net_yr"] = {m: r["vials_yr_low"] * m - opex[1] for m in MARGIN_PER_VIAL}
            r["breakeven_margin_12m"] = (
                opex[1] / r["vials_yr_low"] if r["vials_yr_low"] > 0 else None
            )
            v = r["vials_yr_low"] * WEEKS_PER_YEAR[0] / WEEKS_PER_YEAR[1] * MARGIN_PER_VIAL[0]
            r["worst_net_yr"] = v - opex[2]
        out.append(r)
    return out


def _money(x: float) -> str:
    return f"${x / 1e6:,.1f} M" if abs(x) >= 1e6 else f"${x / 1e3:,.0f} k"


def _rng(t: tuple) -> str:
    return f"{_money(t[1])} (range {_money(t[0])} to {_money(t[2])})"


def _months(x: float | None) -> str:
    return "never (gain not detectable)" if x is None else f"{x:.1f}"


def report(d: dict) -> str:
    rs = rows(d)
    wk = ppt_hours_per_week()
    m = MARGIN_PER_VIAL
    L = [
        "# Illustrative economics (T5.2.4)",
        "",
        "> **Illustrative only. Not a business case.** Simulated, benchmark-parameterized line, "
        "not plant data. Output gains are RESULTS from "
        "[`reports/results_final.json`](../reports/results_final.json); every price and cost "
        "below is a **PLACEHOLDER** with no source, chosen only to show the arithmetic. "
        "Generated by `python -m ffdt.experiments.economics`; do not edit by hand.",
        "",
        "## Inputs",
        "| Input | Value | Type |",
        "|---|---|---|",
        f"| Scheduled production hours per week | {wk:.0f} h (5 days x 2 shifts x 7 h net of "
        "breaks, frozen baseline calendar) | ASSUMPTION (baseline v1.0) |",
        f"| Production weeks per year | {WEEKS_PER_YEAR[1]} (range {WEEKS_PER_YEAR[0]} to "
        f"{WEEKS_PER_YEAR[2]}) | ASSUMPTION |",
        f"| Contribution margin of one extra good vial **sold** | ${m[0]:.2f} / ${m[1]:.2f} / "
        f"${m[2]:.2f} (low / mid / high) | PLACEHOLDER, spans a 20x range on purpose |",
    ]
    for r in rs:
        if r["capex"]:
            L.append(f"| {r['what']}: one-time cost | {_rng(r['capex'])} | PLACEHOLDER |")
        else:
            L.append(
                f"| {r['what']}: fully loaded cost | {_rng(r['opex'])} per year | PLACEHOLDER |"
            )
    L += [
        "",
        "Extra vials per year = (paired gain in good vials per scheduled hour) x "
        f"{wk:.0f} h x {WEEKS_PER_YEAR[1]} weeks, assuming the baseline weekly campaign "
        "(6 batches, same mix) repeats every week. Payback and net value use the **lower end of "
        "the 95% CI** of the gain (a cautious reading) and the mid cost. The worst case "
        f"combines the high cost, the ${MARGIN_PER_VIAL[0]:.2f} margin, the CI low gain and "
        f"{WEEKS_PER_YEAR[0]} weeks.",
        "",
        "## Results",
        f"| Lever | Output gain (95% CI), RESULT | Extra good vials per year, mean (CI low) | "
        f"Payback months at ${m[0]:.2f} / ${m[1]:.2f} / ${m[2]:.2f} per vial | Margin per "
        "vial needed for 12-month payback | Worst case |",
        "|---|---|---|---|---|---|",
    ]
    for r in rs:
        lo, hi = r["pct_ci"]
        gain = f"{r['pct']:+.1%} ({lo:+.1%} to {hi:+.1%})"
        vials = f"{r['vials_yr'] / 1e6:,.2f} M ({r['vials_yr_low'] / 1e6:,.2f} M)"
        if r["capex"]:
            pb = " / ".join(_months(r["payback_months"][x]) for x in m)
            if r["payback_months"][m[0]] is None:
                pb = "never: the gain is not detectable (CI includes zero)"
        else:
            pb = "recurring cost: net per year " + " / ".join(_money(r["net_yr"][x]) for x in m)
        be = r["breakeven_margin_12m"]
        be_s = "n/a" if be is None else f"${be:,.2f}"
        if r["capex"]:
            w = r["worst_months"]
            worst = "never" if w is None else f"payback {w:.1f} months"
        else:
            worst = f"net {_money(r['worst_net_yr'])} per year"
        L.append(f"| {r['what']} | {gain} | {vials} | {pb} | {be_s} | {worst} |")

    by = {r["scenario"]: r for r in rs}
    s50, avi, op = by["sc04_changeover_m50"], by["sc01_avi_plus1"], by["sc03_operator_plus1"]
    L += [
        "",
        "## What this shows (and what it does not)",
        f"- **Changeover reduction pays back fast at any of the placeholder prices**, if the "
        "reduction is achieved (the -25% and -50% levels are ASSUMPTIONS, not measured SMED "
        "results). At the "
        f"mid cost, a -50% SMED program pays back in "
        f"{_months(s50['payback_months'][m[0]])} months even at ${m[0]:.2f} per vial; it "
        f"needs only ${s50['breakeven_margin_12m']:,.2f} per vial to pay back within a year.",
        "- **Why paybacks look so short:** the line makes millions of vials a year, so a "
        "double-digit percentage gain is worth a lot even at cents per vial. The conclusion "
        "therefore barely depends on the placeholder prices, which is the useful finding; the "
        "months themselves are not.",
        "- **A second inspection machine never pays back in this model**, at any price: the "
        "filler is the constraint, so extra inspection capacity adds no detectable output "
        f"(95% CI {avi['pct_ci'][0]:+.1%} to {avi['pct_ci'][1]:+.1%}). This is the Theory of "
        "Constraints point in money terms: capacity at a non-constraint buys nothing.",
        f"- **One more line operator per shift** adds output ({op['pct']:+.1%}) but carries "
        f"a recurring cost; it covers that cost only above about "
        f"${op['breakeven_margin_12m']:,.2f} per vial.",
        "- **Extra output is only worth money if it can be sold.** If demand is fixed, the "
        "same gain shows up instead as fewer scheduled hours (less overtime, or room for "
        "another product), which this note does not value.",
        "- **Not included:** validation and qualification of a changed process (a real "
        "cost for any GMP change), downtime to implement, material and QA release costs per "
        "vial, taxes, discounting, and risk. The placeholder costs are not vendor quotes.",
        "- **Use with real numbers:** replace the PLACEHOLDER rows with site margin and "
        "quoted costs; the RESULT rows stay as they are, still labeled simulated.",
        "",
    ]
    return "\n".join(L)


def write() -> str:
    d = json.loads(FINAL.read_text(encoding="utf-8"))
    text = report(d)
    DOC.write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    print(write())
